/**
 * Translation helper function.
 * Translates $key into active language, falling back to English, then human-readable key.
 */
function t(string $key, array $replace = []): string
{
    $lang = current_lang();
    $catalog = translation_catalog();

    $text = null;
    if (isset($catalog[$lang][$key])) {
        $text = $catalog[$lang][$key];
    } elseif (isset($catalog['en'][$key])) {
        $text = $catalog['en'][$key];
    } else {
        // Fallback: convert 'some_key_name' to 'Some key name'
        $text = ucfirst(str_replace('_', ' ', $key));
    }

    if (!empty($replace)) {
        foreach ($replace as $placeholder => $value) {
            $text = str_replace(':' . $placeholder, (string)$value, $text);
        }
    }

    return (string)$text;
}

/**
 * Echo escaped translated string
 */
function _e(string $key, array $replace = []): void
{
    echo htmlspecialchars(t($key, $replace), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}


