/**
 * Determine the active user language code.
 * Language switching can strictly only be performed on index.php and settings.php.
 * Once chosen, the language persists across the entire website via session, cookie, and database.
 */
function current_lang(): string
{
    if (!empty($GLOBALS['IMALIS_CURRENT_LANG'])) {
        return $GLOBALS['IMALIS_CURRENT_LANG'];
    }

    $valid = available_languages();
    $lang = 'en';

    // Verify current script: language selection is only permitted on index.php and settings.php
    $script = basename($_SERVER['SCRIPT_NAME'] ?? $_SERVER['PHP_SELF'] ?? '');
    $canSelectLanguage = in_array($script, ['index.php', 'settings.php'], true);

    // 1. Explicit GET param (strictly allowed only on index.php and settings.php)
    if (isset($_GET['lang']) && $canSelectLanguage) {
        $candidate = strtolower(trim((string)$_GET['lang']));
        if ($candidate === 'zh' || $candidate === 'zh-cn' || $candidate === 'zh_cn') $candidate = 'zh-Hans';
        if ($candidate === 'zh-tw' || $candidate === 'zh_tw') $candidate = 'zh-Hant';
        if (isset($valid[$candidate])) {
            set_current_lang($candidate);
            return $candidate;
        }
    }

    // 2. Active Session
    if (isset($_SESSION['imali_lang']) && isset($valid[$_SESSION['imali_lang']])) {
        $lang = (string)$_SESSION['imali_lang'];
    } elseif (isset($_SESSION['lang']) && isset($valid[$_SESSION['lang']])) {
        $lang = (string)$_SESSION['lang'];
    // 3. Persistent Cookie
    } elseif (isset($_COOKIE['imali_lang']) && isset($valid[$_COOKIE['imali_lang']])) {
        $lang = (string)$_COOKIE['imali_lang'];
        $_SESSION['imali_lang'] = $lang;
        $_SESSION['lang'] = $lang;
    // 4. Authenticated user database profile
    } elseif (function_exists('is_authenticated') && is_authenticated()) {
        $user = current_user();
        if ($user && !empty($user['preferred_language']) && isset($valid[$user['preferred_language']])) {
            $lang = (string)$user['preferred_language'];
            $_SESSION['imali_lang'] = $lang;
            $_SESSION['lang'] = $lang;
        }
    }

    $GLOBALS['IMALIS_CURRENT_LANG'] = $lang;
    return $lang;
}

/**
 * Helper to build URL for switching language.
 * Strictly confines target to index.php or settings.php.
 */
function language_switch_url(string $lang, ?string $target = null): string
{
    $targetPath = $target ?: (parse_url($_SERVER['REQUEST_URI'] ?? '', PHP_URL_PATH) ?: 'index.php');
    $script = basename($targetPath);
    if (!in_array($script, ['index.php', 'settings.php'], true)) {
        $targetPath = 'index.php';
    }
    return $targetPath . '?lang=' . urlencode($lang);
}

/**
 * Set and persist active language across session, cookie, and database.
 */
function set_current_lang(string $lang): void
{
    $valid = available_languages();
    if (!isset($valid[$lang])) {
        $lang = 'en';
    }

    $GLOBALS['IMALIS_CURRENT_LANG'] = $lang;
    $_SESSION['imali_lang'] = $lang;
    $_SESSION['lang'] = $lang;

    // Set cookie for 1 year across whole domain
    $secure = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off');
    setcookie('imali_lang', $lang, [
        'expires' => time() + (365 * 86400),
        'path' => '/',
        'secure' => $secure,
        'httponly' => false,
        'samesite' => 'Lax',
    ]);

    // Persist to user record in DB and session if logged in
    if (function_exists('is_authenticated') && is_authenticated()) {
        $user = current_user();
        if ($user) {
            if (isset($_SESSION['user']) && is_array($_SESSION['user'])) {
                $_SESSION['user']['preferred_language'] = $lang;
            }
            if (function_exists('database_ready') && database_ready()) {
                try {
                    $stmt = db()->prepare('UPDATE users SET preferred_language = :lang WHERE id = :id');
                    $stmt->execute(['lang' => $lang, 'id' => $user['id']]);
                } catch (Throwable $e) {}
            }
        }
    }
}

/**
 * Returns true if the active language is Right-To-Left (e.g. Arabic)
 */
function is_rtl(): bool
{
    $lang = current_lang();
    $all = available_languages();
    return isset($all[$lang]) && $all[$lang]['dir'] === 'rtl';
}

